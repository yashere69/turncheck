"""Mutation test: does the example suite catch every seeded bug, with no false failures?

Runs the suite once against the clean agent and once per seeded bug, then writes
results/mutation.md. This is the file the README's numbers come from.

    python tools/mutation.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from turncheck.runner import run_scenario  # noqa: E402
from turncheck.scenario import discover, load  # noqa: E402

AGENT = f"python {ROOT / 'examples/agents/shopagent.py'}"
BUGS = [
    "dedup",
    "window",
    "orderid",
    "signature",
    "status",
    "slowack",
    "batch",
    "noretry",
    "phoneonly",
]


def run(bugs: str):
    scs = [load(p) for p in discover(ROOT / "examples/scenarios")]
    return [run_scenario(s, AGENT, {"SHOPAGENT_BUGS": bugs}) for s in scs]


def main() -> int:
    rows = []
    clean = run("")
    clean_fail = [r.scenario.name for r in clean if not r.ok]
    rows.append(("(none — clean agent)", len(clean_fail), ", ".join(clean_fail) or "—"))
    caught = 0
    for bug in BUGS:
        res = run(bug)
        failed = [r.scenario.name for r in res if not r.ok]
        caught += bool(failed)
        rows.append((bug, len(failed), "; ".join(failed) or "NOT CAUGHT"))
    lines = [
        "# Mutation results",
        "",
        "Generated by `python tools/mutation.py`. Do not edit by hand.",
        "",
        f"Seeded bugs caught: **{caught}/{len(BUGS)}**. "
        f"False failures on the clean agent: **{len(clean_fail)}**.",
        "",
        "| Seeded bug | Scenarios failing | Which |",
        "|---|---|---|",
    ]
    lines += [f"| {b} | {n} | {w} |" for b, n, w in rows]
    out = ROOT / "results" / "mutation.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0 if caught == len(BUGS) and not clean_fail else 1


if __name__ == "__main__":
    sys.exit(main())
